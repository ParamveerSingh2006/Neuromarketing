def ensure_columns(df, required, name):
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(
            f"{name} is missing required columns: {missing}\n"
            f"Available columns: {list(df.columns)}"
        )


def savefig(path):
    plt.tight_layout()
    plt.savefig(path, dpi=300, bbox_inches="tight")
    plt.close()


def readable_config(row):
    return (
        f"{row['feature_config']} | "
        f"W-{row['weighting']} | "
        f"F-{row['focal_loss']}"
    )


def clean_feature_config(df):
    """
    Keep the canonical feature configuration labels generated by
    Pipeline-2. This avoids reconstructing them from dimensions.
    """
    valid = set(FEATURE_ORDER)
    bad = sorted(set(df["feature_config"].dropna()) - valid)
    if bad:
        raise ValueError(
            f"Unexpected feature_config values: {bad}"
        )


def mean_sd_string(mean, sd):
    if pd.isna(mean):
        return "NA"
    if pd.isna(sd):
        return f"{mean:.4f}"
    return f"{mean:.4f} ± {sd:.4f}"


def paired_effect_table(subject, group_cols, on_col, off_col):
    """
    Generic paired ON-OFF effect calculation at subject level.
    """
    rows = []

    keys = ["subject"] + group_cols

    for keys_values, g in subject.groupby(keys, dropna=False):
        if not isinstance(keys_values, tuple):
            keys_values = (keys_values,)

        off = g[g[on_col] == "OFF"]
        on = g[g[on_col] == "ON"]

        if len(off) != 1 or len(on) != 1:
            continue

        off_row = off.iloc[0]
        on_row = on.iloc[0]

        row = dict(zip(keys, keys_values))

        for metric in METRICS:
            row[f"off_{metric}"] = off_row[metric]
            row[f"on_{metric}"] = on_row[metric]
            row[f"delta_{metric}"] = (
                on_row[metric] - off_row[metric]
            )

        rows.append(row)

    return pd.DataFrame(rows)


