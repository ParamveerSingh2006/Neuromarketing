def plot_factorial_interaction(interaction, feature, metric):
    d = interaction[
        interaction["feature_config"] == feature
    ].copy()

    if d.empty:
        return

    pivot = d.pivot_table(
        index="focal_loss",
        columns="weighting",
        values=metric,
        aggfunc="mean",
    )

    rows = ["OFF", "ON"]
    cols = ["OFF", "ON"]

    matrix = pivot.reindex(
        index=rows,
        columns=cols,
    )

    fig, ax = plt.subplots(figsize=(6, 5))

    im = ax.imshow(
        matrix.values,
        aspect="auto",
        interpolation="nearest",
    )

    ax.set_xticks([0, 1])
    ax.set_xticklabels(
        ["Weight-OFF", "Weight-ON"]
    )
    ax.set_yticks([0, 1])
    ax.set_yticklabels(
        ["Focal-OFF", "Focal-ON"]
    )

    ax.set_xlabel("Class weighting")
    ax.set_ylabel("Focal loss")
    ax.set_title(
        f"{feature}: mean {METRIC_LABELS[metric]}"
    )

    for i in range(2):
        for j in range(2):
            value = matrix.iloc[i, j]
            if pd.notna(value):
                ax.text(
                    j,
                    i,
                    f"{value:.3f}",
                    ha="center",
                    va="center",
                    fontsize=10,
                )

    fig.colorbar(
        im,
        ax=ax,
        label=METRIC_LABELS[metric],
    )

    savefig(
        OUTPUT_DIR
        / f"05_factorial_{feature.replace('+', '_')}_{metric}.png"
    )


