def generate_report(
    config,
    subject,
    rankings,
    weighting,
    focal,
    winners,
):
    lines = []

    n_subjects = subject["subject"].nunique()
    n_configs = config["configuration"].nunique()

    lines.append(
        "PT_1 PIPELINE-2 RESULTS ANALYSIS"
    )
    lines.append("=" * 70)
    lines.append("")
    lines.append(
        f"Subjects represented: {n_subjects}"
    )
    lines.append(
        f"Configurations: {n_configs}"
    )
    lines.append("")

    if n_subjects != 42:
        lines.append(
            f"NOTE: The result workbook contains {n_subjects} subjects, "
            f"not the expected 42."
        )
        lines.append("")

    lines.append(
        "1. BEST CONFIGURATION BY METRIC"
    )
    lines.append("-" * 70)

    for metric in METRICS:
        r = rankings[metric].iloc[0]

        lines.append(
            f"{METRIC_LABELS[metric]}: "
            f"{r['readable_configuration']} | "
            f"mean={r[f'mean_{metric}']:.4f} | "
            f"SD={r[f'std_{metric}']:.4f}"
        )

    lines.append("")

    lines.append(
        "2. TOP 5 CONFIGURATIONS BY F1"
    )
    lines.append("-" * 70)

    for _, r in rankings["f1"].head(5).iterrows():
        lines.append(
            f"Rank {int(r['rank'])}: "
            f"{r['readable_configuration']} | "
            f"F1={r['mean_f1']:.4f} ± {r['std_f1']:.4f} | "
            f"Accuracy={r['mean_accuracy']:.4f} | "
            f"Kappa={r['mean_kappa']:.4f} | "
            f"BA={r['mean_balanced_accuracy']:.4f}"
        )

    lines.append("")

    lines.append(
        "3. BEST CONFIGURATION FOR EACH EXPERIMENTAL FEATURE SET"
    )
    lines.append("-" * 70)

    for feature in FEATURE_ORDER:
        d = config[
            config["feature_config"] == feature
        ]

        if d.empty:
            continue

        r = d.loc[
            d["mean_f1"].idxmax()
        ]

        lines.append(
            f"{feature}: "
            f"{r['readable_configuration']} | "
            f"F1={r['mean_f1']:.4f} | "
            f"Accuracy={r['mean_accuracy']:.4f} | "
            f"Kappa={r['mean_kappa']:.4f} | "
            f"BA={r['mean_balanced_accuracy']:.4f}"
        )

    lines.append("")

    lines.append(
        "4. CLASS-WEIGHTING EFFECT"
    )
    lines.append("-" * 70)

    if weighting.empty:
        lines.append(
            "No paired weighting effects were available."
        )
    else:
        for focal_state in ["OFF", "ON"]:
            d = weighting[
                weighting["focal_loss"] == focal_state
            ]

            if d.empty:
                continue

            lines.append(
                f"Focal-{focal_state}:"
            )

            for feature in FEATURE_ORDER:
                z = d[
                    d["feature_config"] == feature
                ]

                if z.empty:
                    continue

                lines.append(
                    f"  {feature}: "
                    f"ΔF1={z['delta_f1'].mean():+.4f}, "
                    f"ΔAccuracy={z['delta_accuracy'].mean():+.4f}, "
                    f"ΔKappa={z['delta_kappa'].mean():+.4f}, "
                    f"ΔBA={z['delta_balanced_accuracy'].mean():+.4f}"
                )

    lines.append("")

    lines.append(
        "5. FOCAL-LOSS EFFECT"
    )
    lines.append("-" * 70)

    if focal.empty:
        lines.append(
            "No paired focal-loss effects were available."
        )
    else:
        for weighting_state in ["OFF", "ON"]:
            d = focal[
                focal["weighting"] == weighting_state
            ]

            if d.empty:
                continue

            lines.append(
                f"Weight-{weighting_state}:"
            )

            for feature in FEATURE_ORDER:
                z = d[
                    d["feature_config"] == feature
                ]

                if z.empty:
                    continue

                lines.append(
                    f"  {feature}: "
                    f"ΔF1={z['delta_f1'].mean():+.4f}, "
                    f"ΔAccuracy={z['delta_accuracy'].mean():+.4f}, "
                    f"ΔKappa={z['delta_kappa'].mean():+.4f}, "
                    f"ΔBA={z['delta_balanced_accuracy'].mean():+.4f}"
                )

    lines.append("")

    lines.append(
        "6. SUBJECT-LEVEL WINNERS"
    )
    lines.append("-" * 70)

    for metric in [
        "accuracy",
        "f1",
        "kappa",
        "balanced_accuracy",
    ]:
        d = winners[
            winners["metric"] == metric
        ]

        counts = (
            d["configuration"]
            .value_counts()
            .head(5)
        )

        lines.append(
            f"Top subject-level winner counts by "
            f"{METRIC_LABELS[metric]}:"
        )

        for configuration, count in counts.items():
            label = d.loc[
                d["configuration"] == configuration,
                "readable_configuration",
            ].iloc[0]

            lines.append(
                f"  {label}: {int(count)} subjects"
            )

        lines.append("")

    lines.append(
        "7. INTERPRETATION CAUTION"
    )
    lines.append("-" * 70)
    lines.append(
        "The configuration means are descriptive aggregates of "
        "subject-level out-of-fold results. They should not be treated "
        "as proof that one configuration is universally superior."
    )
    lines.append(
        "Weighting and focal-loss effects should be interpreted from "
        "paired subject-level differences, not only from differences "
        "between aggregate means."
    )
    lines.append(
        "Balanced Accuracy, F1, Accuracy and Kappa capture different "
        "properties of classification performance; no arbitrary combined "
        "score is used by this script."
    )

    return "\n".join(lines)


