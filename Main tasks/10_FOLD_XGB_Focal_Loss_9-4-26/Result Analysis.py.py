def create_rankings(config):
    tables = {}

    for metric in METRICS:
        mean_col = f"mean_{metric}"
        std_col = f"std_{metric}"

        d = config[
            [
                "configuration",
                "readable_configuration",
                "feature_config",
                "weighting",
                "focal_loss",
                "subjects_evaluated",
                "mean_accuracy",
                "std_accuracy",
                "mean_f1",
                "std_f1",
                "mean_kappa",
                "std_kappa",
                "mean_balanced_accuracy",
                "std_balanced_accuracy",
                "mean_precision",
                "std_precision",
                "mean_recall_sensitivity",
                "std_recall_sensitivity",
                "mean_specificity",
                "std_specificity",
                "mean_roc_auc",
                "std_roc_auc",
            ]
        ].copy()

        d = d.sort_values(
            mean_col,
            ascending=False,
        ).reset_index(drop=True)

        d.insert(
            0,
            "rank",
            np.arange(1, len(d) + 1),
        )

        tables[metric] = d

    return tables


def create_weighting_effects(subject):
    """
    Paired effect of Weight-ON minus Weight-OFF.
    Focal state is held constant.
    """
    rows = []

    for focal in ["OFF", "ON"]:
        d = subject[
            subject["focal_loss"] == focal
        ]

        if d.empty:
            continue

        effect = paired_effect_table(
            d,
            group_cols=["feature_config", "focal_loss"],
            on_col="weighting",
            off_col="weighting",
        )

        if not effect.empty:
            rows.append(effect)

    if not rows:
        return pd.DataFrame()

    return pd.concat(
        rows,
        ignore_index=True,
    )


def create_focal_effects(subject):
    """
    Paired effect of Focal-ON minus Focal-OFF.
    Weighting state is held constant.
    """
    rows = []

    for weighting in ["OFF", "ON"]:
        d = subject[
            subject["weighting"] == weighting
        ]

        if d.empty:
            continue

        effect = paired_effect_table(
            d,
            group_cols=["feature_config", "weighting"],
            on_col="focal_loss",
            off_col="focal_loss",
        )

        if not effect.empty:
            rows.append(effect)

    if not rows:
        return pd.DataFrame()

    return pd.concat(
        rows,
        ignore_index=True,
    )


def create_interaction_summary(subject):
    """
    Four-cell factorial summary:
        W-OFF/F-OFF
        W-ON/F-OFF
        W-OFF/F-ON
        W-ON/F-ON

    Values are subject-level means of each metric.
    """
    group_cols = [
        "feature_config",
        "weighting",
        "focal_loss",
    ]

    return (
        subject
        .groupby(group_cols, as_index=False)[METRICS]
        .mean()
    )


def create_subject_winners(subject):
    rows = []

    for metric in METRICS:
        idx = subject.groupby("subject")[metric].idxmax()
        best = subject.loc[idx].copy()
        best["metric"] = metric
        best["best_value"] = best[metric]

        rows.append(
            best[
                [
                    "subject",
                    "metric",
                    "configuration",
                    "readable_configuration",
                    "feature_config",
                    "weighting",
                    "focal_loss",
                    "best_value",
                ]
            ]
        )

    return pd.concat(
        rows,
        ignore_index=True,
    )


def create_feature_summary(config):
    """
    Mean over the 4 W/F branches for each feature configuration.

    This is descriptive only. It should not be interpreted as a model
    comparison because it averages over different experimental states.
    """
    return (
        config
        .groupby("feature_config", as_index=False)[
            [
                "mean_accuracy",
                "mean_f1",
                "mean_kappa",
                "mean_balanced_accuracy",
                "mean_roc_auc",
            ]
        ]
        .mean()
        .set_index("feature_config")
        .reindex(FEATURE_ORDER)
        .reset_index()
    )


